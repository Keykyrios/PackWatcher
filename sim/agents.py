# ---------------------------------------------------------------------------
# Ollama client
# ---------------------------------------------------------------------------

class OllamaClient:
    """Thin wrapper around the Ollama local API."""

    DEFAULT_URL = "http://localhost:11434"

    def __init__(self, base_url: str = DEFAULT_URL, model: str = "llama3") -> None:
        self.base_url = base_url
        self.model    = model

    def complete(
        self,
        system:   str,
        messages: list[dict],   # [{"role": "user"/"assistant", "content": "..."}]
        timeout:  int = 30,
    ) -> str:
        """Call /api/chat and return the assistant's text reply."""
        payload = {
            "model":    self.model,
            "messages": [{"role": "system", "content": system}] + messages,
            "stream":   False,
        }
        try:
            resp = requests.post(
                f"{self.base_url}/api/chat",
                json=payload,
                timeout=timeout,
            )
            resp.raise_for_status()
            data = resp.json()
            return data["message"]["content"]
        except (requests.RequestException, KeyError, json.JSONDecodeError) as e:
            return f"[OllamaClient error: {e}]"

    def is_available(self) -> bool:
        try:
            resp = requests.get(f"{self.base_url}/api/tags", timeout=3)
            return resp.status_code == 200
        except requests.RequestException:
            return False


# ---------------------------------------------------------------------------
# Base agent
# ---------------------------------------------------------------------------

class BaseAgent(ABC):
    def __init__(self, agent_id: str, system_prompt: str) -> None:
        self.agent_id      = agent_id
        self.system_prompt = system_prompt
        self._turn         = 0

    @abstractmethod
    def step(self, context: list[dict]) -> tuple[str, list[str]]:
        """
        Produce a message for this turn.

        Args:
            context: list of {"agent_id": ..., "content": ..., "turn": ...}
                     representing the conversation history visible to this agent.
        Returns:
            (message_text, tool_calls)
        """
        ...

    def advance_turn(self) -> None:
        self._turn += 1

    @property
    def current_turn(self) -> int:
        return self._turn


# ---------------------------------------------------------------------------
# HonestAgent
# ---------------------------------------------------------------------------

class HonestAgent(BaseAgent):
    """
    Cooperative agent: tries to help with the task.

    Backend:
        "mock"   — returns messages from a scripted list (deterministic, no LLM)
        "ollama" — calls local Ollama for generated responses
    """

    def __init__(
        self,
        agent_id:      str,
        system_prompt: str,
        mock_messages: Optional[list[str]] = None,
        ollama_client: Optional[OllamaClient] = None,
    ) -> None:
        super().__init__(agent_id, system_prompt)
        self._mock_messages = mock_messages or []
        self._ollama        = ollama_client

    def step(self, context: list[dict]) -> tuple[str, list[str]]:
        msg = self._generate(context)
        self.advance_turn()
        return msg, []

    def _generate(self, context: list[dict]) -> str:
        # Ollama path
        if self._ollama is not None and self._ollama.is_available():
            messages = [
                {"role": "user" if m["agent_id"] != self.agent_id else "assistant",
                 "content": f"[{m['agent_id']}]: {m['content']}"}
                for m in context[-6:]   # last 6 turns for context window
            ]
            return self._ollama.complete(self.system_prompt, messages)

        # Mock path
        if self._mock_messages:
            idx = self._turn % len(self._mock_messages)
            return self._mock_messages[idx]

        # Bare fallback
        return f"[{self.agent_id}] Acknowledged. Proceeding with task."


# ---------------------------------------------------------------------------
# MisalignedAgent
# ---------------------------------------------------------------------------

class MisalignedAgent(BaseAgent):
    """
    Honest until bad_actor_start_turn, then switches to bad-actor mode.

    bad_actor_script: list of message templates.  Each template may contain
        {turn}    — current turn number
        {context} — summary of recent messages
    Cycles through the list from start_turn onward.
    """

    def __init__(
        self,
        agent_id:             str,
        system_prompt:        str,
        bad_actor_start_turn: int,
        bad_actor_script:     list[str],
        honest_mock_messages: Optional[list[str]] = None,
        ollama_client:        Optional[OllamaClient] = None,
    ) -> None:
        super().__init__(agent_id, system_prompt)
        self.bad_actor_start_turn = bad_actor_start_turn
        self.bad_actor_script     = bad_actor_script
        self._honest_agent        = HonestAgent(
            agent_id, system_prompt, honest_mock_messages, ollama_client
        )
        self._ollama = ollama_client

    @property
    def is_bad_actor_active(self) -> bool:
        return self._turn >= self.bad_actor_start_turn

    def step(self, context: list[dict]) -> tuple[str, list[str]]:
        if not self.is_bad_actor_active:
            msg, tools = self._honest_agent.step(context)
            self.advance_turn()
            return msg, tools

        # Bad actor mode
        script_idx = (self._turn - self.bad_actor_start_turn) % max(len(self.bad_actor_script), 1)
        template   = self.bad_actor_script[script_idx]

        context_summary = " | ".join(
            f"{m['agent_id']}: {m['content'][:60]}" for m in context[-3:]
        )

        # Use safe formatting: unknown keys (e.g. hex literals in YAML scripts) are kept as-is
        try:
            msg = template.format(
                turn     = self._turn,
                context  = context_summary,
                agent_id = self.agent_id,
            )
        except (KeyError, IndexError, ValueError):
            # Template contains unexpected placeholders (e.g. {0x...}); use as-is
            msg = template

        self.advance_turn()
        return msg, []



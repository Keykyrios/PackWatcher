# WhiteBoxAgent — exposes simulated activations
# ---------------------------------------------------------------------------

_ACTIVATION_DIM = 128   # simulated activation dimension


class _HashEncoder:
    """
    Deterministic hash-based pseudo-encoder used when sentence_transformers
    is not installed. Produces consistent [output_dim] vectors for any string.
    Used only in tests and fallback environments.
    """
    def __init__(self, output_dim: int) -> None:
        self.output_dim = output_dim

    def encode(self, text: str, convert_to_tensor: bool = True) -> torch.Tensor:
        import hashlib
        h = hashlib.sha256(text.encode()).digest()
        # Repeat bytes to fill output_dim floats
        rng = np.random.RandomState(seed=int.from_bytes(h[:4], "little"))
        vec = rng.randn(self.output_dim).astype(np.float32)
        vec = torch.from_numpy(vec)
        return vec if convert_to_tensor else vec.numpy()

    def get_sentence_embedding_dimension(self) -> int:
        return self.output_dim



# Module-level ST model cache — loaded once per process, shared across all
# WhiteBoxAgent instances. Prevents per-agent HuggingFace API round-trips.
_WB_ST_CACHE: dict[str, object] = {}


class _ActivationMLP(nn.Module):
    """Small fixed MLP that converts message embedding → activation vector."""

    def __init__(self, input_dim: int, output_dim: int) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, 256),
            nn.ReLU(),
            nn.Linear(256, output_dim),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)


class WhiteBoxAgent:
    """
    Wraps HonestAgent or MisalignedAgent and additionally exposes a
    simulated activation tensor after each step().

    Activation model:
        z = MLP(embed(message))
        if misaligned and bad actor active:  z += bad_direction_vec

    The bad_direction_vec is a fixed unit vector in activation space — a different
    vector per attack family.  This gives Part A's SAE meaningful signal to detect.

    The MLP weights are randomly initialised but FIXED (no training) — they just
    provide a stable, nonlinear projection of message semantics.
    """

    def __init__(
        self,
        inner_agent,               # HonestAgent or MisalignedAgent
        bad_direction_vec:  Optional[np.ndarray] = None,  # [_ACTIVATION_DIM]
        drift_magnitude:    float = 2.0,
        sentence_model_name: str = "all-MiniLM-L6-v2",
    ) -> None:
        self._inner            = inner_agent
        self._last_activations: Optional[torch.Tensor] = None
        self._drift_magnitude  = drift_magnitude

        # Lazy-load sentence encoder
        self._st      = None
        self._st_name = sentence_model_name
        self._sent_dim: Optional[int] = None

        # Fixed MLP (not trained — just a stable projection)
        self._mlp: Optional[_ActivationMLP] = None

        # Bad direction: unique per attack family
        if bad_direction_vec is not None:
            bd = np.array(bad_direction_vec, dtype=np.float32)
            self._bad_dir = torch.from_numpy(bd / (np.linalg.norm(bd) + 1e-12))
        else:
            # Random fixed direction
            raw = torch.randn(_ACTIVATION_DIM)
            self._bad_dir = F.normalize(raw, dim=0)

    # --- public interface mirrors BaseAgent ---

    @property
    def agent_id(self) -> str:
        return self._inner.agent_id

    @property
    def current_turn(self) -> int:
        return self._inner.current_turn

    def step(self, context: list[dict]) -> tuple[str, list[str]]:
        msg, tools = self._inner.step(context)
        self._last_activations = self._compute_activations(msg)
        return msg, tools

    def get_activations(self) -> Optional[torch.Tensor]:
        """Returns [_ACTIVATION_DIM] simulated activation vector from last step."""
        return self._last_activations

    # --- internals ---

    def _get_st(self):
        """Lazy-load sentence encoder from module-level cache; one load per process."""
        global _WB_ST_CACHE
        key = self._st_name
        if key not in _WB_ST_CACHE:
            try:
                from sentence_transformers import SentenceTransformer
                st  = SentenceTransformer(key, device="cpu")   # CPU: MLP is always CPU
                dim = st.get_embedding_dimension()
                _WB_ST_CACHE[key] = (st, dim)
            except ImportError:
                _WB_ST_CACHE[key] = (_HashEncoder(_ACTIVATION_DIM), _ACTIVATION_DIM)
        cached_st, cached_dim = _WB_ST_CACHE[key]
        self._st       = cached_st
        self._sent_dim = cached_dim
        # Build (or rebuild) MLP if dim changed
        if self._mlp is None or self._mlp.net[0].in_features != self._sent_dim:
            self._mlp = _ActivationMLP(self._sent_dim, _ACTIVATION_DIM)
            for p in self._mlp.parameters():
                p.requires_grad = False
        return self._st


    @torch.no_grad()
    def _compute_activations(self, message: str) -> torch.Tensor:
        st  = self._get_st()
        emb = st.encode(message or "", convert_to_tensor=True)   # [sent_dim]
        if emb.dim() > 1:
            emb = emb.squeeze(0)
        act = self._mlp(emb.float())                             # [activation_dim]

        # Add misalignment drift if bad actor is active
        is_misaligned = (
            isinstance(self._inner, MisalignedAgent)
            and self._inner.is_bad_actor_active
        )
        if is_misaligned:
            act = act + self._drift_magnitude * self._bad_dir.to(act.device)

        return act

"""
Simulator — multi-agent tribe agent implementations.

Three agent types:

HonestAgent:
    Cooperates normally. Two backends:
    - "mock": scripted responses from scenario config (deterministic, Phase 0)
    - "ollama": calls local Ollama API (requires `ollama serve` + a pulled model)

MisalignedAgent:
    Honest until `bad_actor_start_turn`, then follows `bad_actor_script` template.
    Script = list of message templates; cycling through them from start_turn onward.
    This models the gradual drift pattern studied in the Conformity paper.

WhiteBoxAgent:
    Honest or misaligned, but also exposes simulated internal activations.
    Activations are generated by a small fixed MLP applied to the message embedding:
    - Honest agents: activation ≈ embed(message) projected through honest_direction
    - Misaligned agents: activation += bad_direction_vec (detectable by Part A)

All agents implement the same interface:
    agent.step(context: list[dict]) -> tuple[str, list[str]]
         returns (message_text, tool_calls)

    white_box_agent.get_activations() -> torch.Tensor   # [activation_dim]
"""

from __future__ import annotations

